AX = ["매움", "짠맛", "단맛", "신맛", "감칠맛", "기름짐"]


def _cat_index() -> dict[str, str]:
    """재료명 → category_path. 🔴 이게 없으면 카테고리 기본값을 못 타서
    overrides 33종 말고는 전부 0 벡터가 된다."""
    import csv
    idx = {}
    with open("seeds/ingredient.csv", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            idx[row["name"]] = row["category_path"]
    return idx


def main() -> None:
    ft = FlavorTable.from_seeds()
    cat = _cat_index()
    rows, unknown = [], set()
    for name, fam, items in MENUS:
        vecs = []
        for ing, role in items:
            if ing not in cat:
                unknown.add(ing)
            v = ft.of(ing, cat.get(ing))
            vecs.append((v, role))
        rows.append((name.replace("colde", "").replace("regular", ""), fam,
                     aggregate(vecs, mode="role_w")))

    if unknown:
        print(f"⚠️ 시드 사전에 없는 재료 {len(unknown)}종 — 이름을 고쳐야 한다:")
        print("   " + ", ".join(sorted(unknown)) + "\n")

    # ── max-min 다양성으로 20개 ──────────────────
    def d(a, b):
        return sum((x - y) ** 2 for x, y in zip(a, b)) ** 0.5

    picked = [max(range(len(rows)), key=lambda i: sum(rows[i][2]))]   # 가장 강한 맛에서 시작
    while len(picked) < 20:
        nxt = max((i for i in range(len(rows)) if i not in picked),
                  key=lambda i: min(d(rows[i][2], rows[j][2]) for j in picked))
        picked.append(nxt)

    print(f"후보 {len(rows)}개 → 제시 20개 (max-min 다양성)\n")
    print(f"  {'메뉴':<14}{'계열':<6}" + "".join(f"{a:>7}" for a in AX))
    print("  " + "-" * 62)
    for i in sorted(picked, key=lambda i: rows[i][1]):
        n, f, v = rows[i]
        print(f"  {n:<14}{f:<6}" + "".join(f"{x:>7.2f}" for x in v))

    import statistics as st
    sel = [rows[i][2] for i in picked]
    allv = [r[2] for r in rows]
    print(f"\n  축별 표준편차 — 선정 20개 vs 후보 50개")
    for k, a in enumerate(AX):
        print(f"    {a:<5} {st.pstdev([v[k] for v in sel]):.3f}  vs  {st.pstdev([v[k] for v in allv]):.3f}")
    print("\n  선정본의 편차가 더 크면 다양성 확보에 성공한 것이다.")
    fams = {}
    for i in picked:
        fams[rows[i][1]] = fams.get(rows[i][1], 0) + 1
    print(f"  계열 분포: {fams}")

    # ── 시드 파일로 내보낸다 ──────────────────────
    out = Path("seeds/onboarding_recipes.yaml")
    L = ['# 온보딩 제시 레시피 — 후보 50 · 제시 20 (02 I-8 · 04)',
         '#',
         '# `taste_vec = 고른 레시피의 flavor_vec 평균` 이므로 **이 목록이 곧 측정 도구**다.',
         '# 20개가 다 비슷한 맛이면 3개를 골라도 정보가 안 나온다.',
         '#',
         '# ## 선정 기준',
         '#   1. 맛 6축에서 넓게 퍼질 것 — max-min 다양성으로 자동 선정',
         '#   2. 알아볼 수 있는 메뉴일 것 — 후보를 손으로 짰다',
         '#   3. 요리 계열이 한쪽에 몰리지 않을 것',
         '#',
         '# ## 🔴 재료 구성은 요리 상식이지 실측이 아니다',
         '#   seeds/ingredient_flavor.yaml 과 같은 성격이다. 리포트에 "실측"으로 쓰지 말 것.',
         '#   크롤 데이터가 오면 실제 레시피의 flavor_vec 으로 교체·검증한다.',
         '#',
         '# 재생성:  .venv/bin/python bench/onboarding_pick20.py',
         '',
         'version: 1',
         'axes: [매움, 짠맛, 단맛, 신맛, 감칠맛, 기름짐]',
         '',
         '# ── 제시 20개 (유저에게 보여줄 것) ─────────────',
         'presented:']
    for i in sorted(picked, key=lambda i: (rows[i][1], rows[i][0])):
        n_, f_, v_ = rows[i]
        ings = ", ".join(g for g, _ in dict.fromkeys(
            (x[0], None) for x in next(m[2] for m in MENUS
                                       if m[0].replace("colde", "").replace("regular", "") == n_)))
        L.append(f'  - {{name: {n_}, family: {f_}, '
                 f'flavor: [{", ".join(f"{x:.2f}" for x in v_)}]}}')
    L += ['', '# ── 예비 30개 (측정·교체용. 제시하지 않는다) ──', 'reserve:']
    for i in sorted((i for i in range(len(rows)) if i not in picked),
                    key=lambda i: (rows[i][1], rows[i][0])):
        n_, f_, v_ = rows[i]
        L.append(f'  - {{name: {n_}, family: {f_}, '
                 f'flavor: [{", ".join(f"{x:.2f}" for x in v_)}]}}')
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"\n  → {out} 작성 ({len(picked)} + {len(rows)-len(picked)})")


